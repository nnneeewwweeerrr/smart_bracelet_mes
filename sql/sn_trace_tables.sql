-- ============================================
-- SN唯一码全生命周期追溯 扩展表
-- ============================================

-- 1. 产品SN码主表（一片一码，全生命周期唯一标识）
DROP TABLE IF EXISTS `product_sn`;
CREATE TABLE `product_sn` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
  `sn_code` VARCHAR(100) NOT NULL COMMENT 'SN唯一编码',
  `product_id` BIGINT NOT NULL COMMENT '产品ID',
  `product_code` VARCHAR(50) COMMENT '产品编码',
  `product_name` VARCHAR(200) COMMENT '产品名称',
  `work_order_id` BIGINT COMMENT '所属工单ID',
  `work_order_no` VARCHAR(50) COMMENT '工单号',
  `order_id` BIGINT COMMENT '关联订单ID',
  `order_no` VARCHAR(50) COMMENT '订单号',
  `customer_id` BIGINT COMMENT '客户ID',
  `customer_name` VARCHAR(200) COMMENT '客户名称',
  `status` INT DEFAULT 0 COMMENT '状态：0在产 1成品 2已出库 3已售后',
  `production_date` DATETIME COMMENT '生产日期',
  `warehouse_id` BIGINT COMMENT '仓库ID',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_sn_code` (`sn_code`),
  KEY `idx_work_order_id` (`work_order_id`),
  KEY `idx_product_id` (`product_id`),
  KEY `idx_order_id` (`order_id`),
  KEY `idx_customer_id` (`customer_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='产品SN唯一码主表';

-- 2. SN物料追溯表（记录每个SN使用的物料批次）
DROP TABLE IF EXISTS `sn_material_trace`;
CREATE TABLE `sn_material_trace` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
  `sn_id` BIGINT NOT NULL COMMENT 'SN ID',
  `sn_code` VARCHAR(100) NOT NULL COMMENT 'SN编码',
  `material_id` BIGINT NOT NULL COMMENT '物料ID',
  `material_code` VARCHAR(50) COMMENT '物料编码',
  `material_name` VARCHAR(200) COMMENT '物料名称',
  `batch_no` VARCHAR(100) COMMENT '物料批次号',
  `supplier_id` BIGINT COMMENT '供应商ID',
  `quantity` DECIMAL(10,2) DEFAULT 1 COMMENT '用量',
  `process_id` BIGINT COMMENT '上料工序ID',
  `operator_id` BIGINT COMMENT '操作工ID',
  `operator_name` VARCHAR(100) COMMENT '操作工姓名',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`),
  KEY `idx_sn_id` (`sn_id`),
  KEY `idx_sn_code` (`sn_code`),
  KEY `idx_material_id` (`material_id`),
  KEY `idx_batch_no` (`batch_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='SN物料追溯明细';

-- 3. SN生产过程追溯表（各工序加工记录）
DROP TABLE IF EXISTS `sn_process_trace`;
CREATE TABLE `sn_process_trace` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
  `sn_id` BIGINT NOT NULL COMMENT 'SN ID',
  `sn_code` VARCHAR(100) NOT NULL COMMENT 'SN编码',
  `process_id` BIGINT NOT NULL COMMENT '工序ID',
  `process_name` VARCHAR(100) COMMENT '工序名称',
  `process_code` VARCHAR(50) COMMENT '工序编码',
  `sort_order` INT DEFAULT 0 COMMENT '工序顺序',
  `worker_id` BIGINT COMMENT '操作工ID',
  `worker_name` VARCHAR(100) COMMENT '操作工姓名',
  `equipment_id` BIGINT COMMENT '设备ID',
  `equipment_name` VARCHAR(100) COMMENT '设备名称',
  `start_time` DATETIME COMMENT '开始时间',
  `end_time` DATETIME COMMENT '结束时间',
  `status` INT DEFAULT 0 COMMENT '状态：0进行中 1完成 2异常',
  `process_params` TEXT COMMENT '工艺参数(JSON)',
  `remark` VARCHAR(500) COMMENT '备注',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`),
  KEY `idx_sn_id` (`sn_id`),
  KEY `idx_sn_code` (`sn_code`),
  KEY `idx_process_id` (`process_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='SN生产过程追溯明细';

-- 4. SN质检追溯表（全流程检验记录）
DROP TABLE IF EXISTS `sn_quality_trace`;
CREATE TABLE `sn_quality_trace` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
  `sn_id` BIGINT NOT NULL COMMENT 'SN ID',
  `sn_code` VARCHAR(100) NOT NULL COMMENT 'SN编码',
  `task_id` BIGINT COMMENT '质检任务ID',
  `task_no` VARCHAR(50) COMMENT '质检任务号',
  `task_type` VARCHAR(20) COMMENT '质检类型：IQC/PQC/OQC',
  `process_id` BIGINT COMMENT '关联工序ID',
  `process_name` VARCHAR(100) COMMENT '工序名称',
  `check_item` VARCHAR(200) COMMENT '检验项',
  `standard_value` VARCHAR(200) COMMENT '标准值',
  `actual_value` VARCHAR(200) COMMENT '实际值',
  `result` INT COMMENT '检验结果：1合格 0不合格',
  `inspector_id` BIGINT COMMENT '检验员ID',
  `inspector_name` VARCHAR(100) COMMENT '检验员姓名',
  `defect_type` VARCHAR(100) COMMENT '不良类型',
  `defect_desc` VARCHAR(500) COMMENT '不良描述',
  `check_time` DATETIME COMMENT '检验时间',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`),
  KEY `idx_sn_id` (`sn_id`),
  KEY `idx_sn_code` (`sn_code`),
  KEY `idx_task_id` (`task_id`),
  KEY `idx_result` (`result`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='SN质检追溯明细';

